import { writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const schemaUrl =
  process.env.OPENAPI_SCHEMA_URL ?? "https://localhost/api/doc.json"
const outputPath = fileURLToPath(
  new URL("../src/libs/api/schema.d.ts", import.meta.url)
)

const isLocalHost = ["localhost", "127.0.0.1"].includes(
  new URL(schemaUrl).hostname
)

if (isLocalHost) {
  // The local Symfony dev server uses a self-signed certificate. Only ever
  // relax TLS verification for localhost/127.0.0.1 — never for a real host.
  console.warn(
    `[generate-api-types] ${schemaUrl} looks like a local dev host — disabling TLS verification for this fetch only.`
  )
  process.env.NODE_TLS_REJECT_UNAUTHORIZED = "0"
}

const ast = await openapiTS(new URL(schemaUrl))
const banner = `/* eslint-disable */\n/**\n * Auto-generated by \`npm run api:types\` from ${schemaUrl}.\n * Do not edit by hand — re-run the script instead.\n */\n\n`

await writeFile(outputPath, banner + astToString(ast))

console.warn(`[generate-api-types] wrote ${outputPath}`)
